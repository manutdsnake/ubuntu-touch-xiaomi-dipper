#!/usr/bin/env python3
"""Generate the Windows installer.

    tools/make-windows-installer.py

Reads installer/device.sh and installer/install-windows.ps1 and writes
install-windows.cmd: a batch file that runs the PowerShell part below its
#PSSTART line, with the device settings in front. It does the same steps as
install.sh and needs nothing but Windows 10 1803+ (curl.exe, tar.exe).
"""
import os
import re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

HEADER = """@echo off
rem Ubuntu Touch installer for the {name} ({codename}) on Windows.
rem Double-click it. Generated by tools/make-windows-installer.py.
setlocal
set "UT_SELF=%~f0"
powershell -NoProfile -ExecutionPolicy Bypass -Command "$s=[IO.File]::ReadAllText($env:UT_SELF); $m='#'+'PS'+'START'; iex $s.Substring($s.IndexOf($m)+$m.Length)"
echo.
pause
exit /b
#PSSTART
"""
SCALARS = ("NAME", "CODENAME", "REPO", "DT_MODEL_MATCH", "FIRMWARE_NAME", "FIRMWARE_URL",
           "FIRMWARE_SHA256", "FIRMWARE_ARCHIVE", "FIRMWARE_SIZE")
ARRAYS = ("RECOVERY_IMAGES", "BASE", "FIRMWARE")


def device_settings():
    with open(os.path.join(HERE, "installer", "device.sh"), encoding="utf-8") as f:
        text = f.read()
    scalars = dict(re.findall(r'^([A-Z_0-9]+)="([^"]*)"', text, re.M))
    arrays = {}
    for name, body in re.findall(r"^([A-Z_0-9]+)=\((.*?)\)", text, re.M | re.S):
        arrays[name] = [a or b for a, b in re.findall(r'"([^"]*)"|(\S+)', body)]
    return scalars, arrays


def ps(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    scalars, arrays = device_settings()
    out = [HEADER.format(name=scalars["NAME"], codename=scalars["CODENAME"])]
    for k in SCALARS:
        out.append("$%s = %s\n" % (k, ps(scalars[k])))
    for k in ARRAYS:
        out.append("$%s = @(\n%s\n)\n" % (k, ",\n".join("    " + ps(v) for v in arrays[k])))
    out.append("\n")
    with open(os.path.join(HERE, "installer", "install-windows.ps1"), encoding="utf-8") as f:
        out.append(f.read())
    data = "".join(out).replace("\r\n", "\n").replace("\n", "\r\n")
    # cmd.exe and Windows PowerShell read the file in the ANSI code page.
    data.encode("ascii")
    path = os.path.join(HERE, "install-windows.cmd")
    with open(path, "w", encoding="ascii", newline="") as f:
        f.write(data)
    print(path)


if __name__ == "__main__":
    main()
